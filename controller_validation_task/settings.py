# Serialization
# ---------------------------------------------------------------------------


def _filter_known(data: Mapping[str, Any], cls: type) -> dict[str, Any]:
    """Drop keys ``cls`` does not declare, logging once at INFO.

    Forward compatibility: a config.json written by a newer version (or one
    with a stray ``_comment``) still loads instead of raising.
    """
    known = {f.name for f in dataclasses.fields(cls)}
    unknown = [k for k in data if k not in known]
    if unknown:
        log.info("Ignoring unknown %s keys in config.json: %s", cls.__name__, unknown)
    return {k: v for k, v in data.items() if k in known}


def _tuple_or_none(value: Any) -> tuple | None:
    return None if value is None else tuple(value)


def _str_tuple(value: Any) -> tuple[str, ...]:
    """Accept ``"s"`` as readily as ``["5", "percent"]``.

    A single key is the common case, and quoting it as a bare string is what
    anyone hand-editing config.json will do.

    >>> _str_tuple("s")
    ('s',)
    >>> _str_tuple(["5", "percent"])
    ('5', 'percent')
    """
    return (value,) if isinstance(value, str) else tuple(str(v) for v in value)


#: Per-section coercions applied after JSON load, so lists become the tuples
#: the frozen dataclasses declare (JSON has no tuple type).
_COERCE: dict[str, dict[str, Callable[[Any], Any]]] = {
    "display": {"window_size": _tuple_or_none},
    "design": {
        "keys": tuple,
        "conditions": tuple,
        "long_duration_range": tuple,
        "isi_range": _tuple_or_none,
    },
    "sync": {"signal": _str_tuple},
}


def _section_from_dict(data: Mapping[str, Any], cls: type, name: str):
    kwargs = _filter_known(data, cls)
    for key, fn in _COERCE.get(name, {}).items():
        if key in kwargs:
            kwargs[key] = fn(kwargs[key])
    return cls(**kwargs)


def from_dict(data: Mapping[str, Any]) -> Settings:
    """Build :class:`Settings` from a parsed config dict (defaults for gaps)."""
    version = data.get("schema_version", SCHEMA_VERSION)
    if version != SCHEMA_VERSION:
        raise ValueError(
            f"config.json has schema_version {version}, but this version of "
            f"controller_validation_task expects {SCHEMA_VERSION}. There is no "
            f"migration path by design: delete config.json and re-run the task "
            f"to regenerate it with the wizard."
        )

    triggers_data = dict(data.get("triggers") or {})
    codes_data = triggers_data.pop("codes", None)
    triggers = _section_from_dict(triggers_data, TriggerSettings, "triggers")
    if codes_data:
        triggers = replace(
            triggers, codes=TriggerCodes(**_filter_known(codes_data, TriggerCodes))
        )

    return Settings(
        schema_version=SCHEMA_VERSION,
        display=_section_from_dict(data.get("display") or {}, DisplaySettings, "display"),
        paths=_section_from_dict(data.get("paths") or {}, PathSettings, "paths"),
        design=_section_from_dict(data.get("design") or {}, DesignSettings, "design"),
        input=_section_from_dict(data.get("input") or {}, InputSettings, "input"),
        sync=_section_from_dict(data.get("sync") or {}, SyncSettings, "sync"),
        triggers=triggers,
    )


def to_dict(settings: Settings) -> dict[str, Any]:
    """Serialize to a JSON-ready dict (tuples become lists)."""

    def _plain(value: Any) -> Any:
        if isinstance(value, tuple):
            return list(value)
        if isinstance(value, Path):
            return str(value)
        return value

    out: dict[str, Any] = {"schema_version": settings.schema_version}
    for section in ("display", "paths", "design", "input", "sync", "triggers"):
        obj = getattr(settings, section)
        out[section] = {
            f.name: (
                dataclasses.asdict(getattr(obj, f.name))
                if dataclasses.is_dataclass(getattr(obj, f.name))
                else _plain(getattr(obj, f.name))
            )
            for f in dataclasses.fields(obj)
        }
    return out


def load_from_file(config_path: str | os.PathLike[str]) -> Settings:
    """Read and parse a config.json (no env / CLI layering, no validation)."""
    raw = json.loads(Path(config_path).read_text(encoding="utf-8"))
    return from_dict(raw)


def save(settings: Settings, config_path: str | os.PathLike[str]) -> Path:
    """Validate then atomically write ``settings`` to ``config_path``."""
    _validate(settings)
    p = Path(config_path)
    p.parent.mkdir(parents=True, exist_ok=True)
    tmp = p.with_suffix(p.suffix + ".tmp")
    tmp.write_text(json.dumps(to_dict(settings), indent=2, sort_keys=True) + "\n", encoding="utf-8")
    os.replace(tmp, p)
    return p


