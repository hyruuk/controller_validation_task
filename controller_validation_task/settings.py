def _parse_bool(val: str) -> bool:
    return val.strip().lower() not in ("0", "false", "no", "off", "")


def _parse_opt_int(val: str) -> int | None:
    return None if val.strip() == "" else int(val)


def _parse_keys(val: str) -> tuple[str, ...]:
    """Comma-separated key names, for the one-line-per-setting env format.

    >>> _parse_keys("s")
    ('s',)
    >>> _parse_keys("5, percent")
    ('5', 'percent')
    """
    return tuple(part.strip() for part in val.split(",") if part.strip())


#: env var -> (section, field, parser). Declarative so the .env.example file
#: and this table can be checked against each other by eye.
_ENV_KEYS: dict[str, tuple[str, str, Any]] = {
    "CVT_OUTPUT_ROOT": ("paths", "output_root", str),
    "CVT_ASSETS_DIR": ("paths", "assets_dir", str),
    "CVT_LAYOUT_FILE": ("paths", "layout_file", str),
    "CVT_N_RUNS": ("design", "n_runs", int),
    "CVT_LR_MODE": ("design", "lr_mode", "bool"),
    "CVT_TR": ("design", "tr", float),
    "CVT_SEED": ("design", "seed", "opt_int"),
    "CVT_SYNC_MODE": ("sync", "mode", str),
    "CVT_SYNC_BACKEND": ("sync", "backend", str),
    "CVT_SYNC_PORT": ("sync", "port", str),
    "CVT_SYNC_SIGNAL": ("sync", "signal", "keys"),
    "CVT_TRIGGER_BACKEND": ("triggers", "backend", str),
    "CVT_TRIGGER_PORT": ("triggers", "port", str),
    "LSL_STREAM_NAME": ("triggers", "lsl_stream_name", str),
    "LSL_STREAM_TYPE": ("triggers", "lsl_stream_type", str),
    "LSL_STREAM_SOURCE_ID": ("triggers", "lsl_stream_source_id", str),
    "EXP_WIN_FULLSCR": ("display", "fullscreen", "bool"),
    "EXP_WIN_SCREEN": ("display", "screen_index", int),
}

_PARSERS: dict[Any, Callable[[str], Any]] = {
    "bool": _parse_bool,
    "opt_int": _parse_opt_int,
    "keys": _parse_keys,
}


def _apply_env(settings: Settings, env: Mapping[str, str]) -> Settings:
    patches: dict[str, dict[str, Any]] = {}
    for var, (section, fieldname, kind) in _ENV_KEYS.items():
        if var not in env:
            continue
        parser = _PARSERS.get(kind, kind)
        try:
            patches.setdefault(section, {})[fieldname] = parser(env[var])
        except (TypeError, ValueError) as exc:
            raise ValueError(f"Cannot parse environment variable {var}={env[var]!r}: {exc}") from exc

    # EXP_WIN_W / EXP_WIN_H compose one field, so they don't fit the table.
    if "EXP_WIN_W" in env and "EXP_WIN_H" in env:
        patches.setdefault("display", {})["window_size"] = (
            int(env["EXP_WIN_W"]),
            int(env["EXP_WIN_H"]),
        )

    return _apply_patches(settings, patches)


#: CLI dest -> (section, field). Values of ``None`` mean "flag not given".
_CLI_KEYS: dict[str, tuple[str, str]] = {
    "output_root": ("paths", "output_root"),
    "layout_file": ("paths", "layout_file"),
    "n_runs": ("design", "n_runs"),
    "lr_mode": ("design", "lr_mode"),
    "fullscreen": ("display", "fullscreen"),
    "screen_index": ("display", "screen_index"),
    "window_size": ("display", "window_size"),
    "instruction_duration": ("display", "instruction_duration"),
    "sync_mode": ("sync", "mode"),
    "sync_backend": ("sync", "backend"),
    "sync_port": ("sync", "port"),
    "sync_signal": ("sync", "signal"),
    "trigger_backend": ("triggers", "backend"),
    "trigger_port": ("triggers", "port"),
}


def _apply_cli(settings: Settings, overrides: Mapping[str, Any]) -> Settings:
    patches: dict[str, dict[str, Any]] = {}
    for name, value in overrides.items():
        if value is None or name not in _CLI_KEYS:
            continue
        section, fieldname = _CLI_KEYS[name]
        patches.setdefault(section, {})[fieldname] = value
    return _apply_patches(settings, patches)


def _apply_patches(settings: Settings, patches: Mapping[str, dict[str, Any]]) -> Settings:
    if not patches:
        return settings
    sections = {
        name: replace(getattr(settings, name), **patch) for name, patch in patches.items()
    }
    return replace(settings, **sections)


def load(
    config_path: str | os.PathLike[str] | None = None,
    env: Mapping[str, str] | None = None,
    cli_overrides: Mapping[str, Any] | None = None,
) -> Settings:
    """Build the effective settings from every layer, then validate.

    Args:
        config_path:   config.json to read; skipped silently if it is missing,
                       so a fresh checkout runs on defaults.
        env:           Environment mapping; defaults to ``os.environ``.
        cli_overrides: ``{dest: value}`` from argparse. ``None`` values mean
                       "flag not supplied" and are ignored.

    Raises:
        ValueError: the merged configuration is invalid (see :func:`_validate`).
    """
    settings = default_settings()
    if config_path is not None and Path(config_path).exists():
        settings = load_from_file(config_path)
    settings = _apply_env(settings, os.environ if env is None else env)
    if cli_overrides:
        settings = _apply_cli(settings, cli_overrides)
    _validate(settings)
    return settings


