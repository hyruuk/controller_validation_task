"""Configuration: schema, layered loading, and validation.

One ``config.json`` at the repo root holds every knob. It is generated by the
first-run wizard (:mod:`controller_validation_task.gui`) and gitignored, so
each rig keeps its own ports and display setup.

Precedence — **later wins**::

    defaults (the dataclasses below)
      < config.json
        < environment variables / .env
          < CLI flags

Design notes worth keeping:

* Every section is a ``frozen`` dataclass, so settings cannot be mutated
  halfway through a run; overrides are applied with :func:`dataclasses.replace`.
* Unknown JSON keys are dropped with an INFO log rather than raising, so a
  config written by a newer version still loads (forward compatibility).
* Missing keys fall back to the dataclass default, so a hand-written partial
  config works.
* :func:`_validate` raises ``ValueError`` with a message that explains *why*
  the constraint exists and what to change — these are read by an operator
  setting up a rig, not by a developer.

Pure module: stdlib + the marker code dataclass. No psychopy import.
"""

from __future__ import annotations

import dataclasses
import json
import logging
import os
from collections.abc import Callable, Mapping
from dataclasses import dataclass, field, replace
from pathlib import Path
from typing import Any, Literal

from controller_validation_task.design import DEFAULT_CONDITIONS, DEFAULT_KEYS
from controller_validation_task.markers import TriggerCodes

log = logging.getLogger(__name__)

#: Bumped only on a breaking change. A mismatch is a hard error telling the
#: operator to delete config.json and re-run the wizard — there is no
#: migration path, deliberately.
SCHEMA_VERSION = 1

TriggerBackend = Literal["lsl", "serial", "parallel", "null"]
SyncMode = Literal["send", "wait", "none"]
SyncBackend = Literal["none", "serial", "parallel", "lsl", "key", "keyboard", "markers"]

#: Sync backends that physically write to a port and therefore need one.
_PORT_BACKENDS = ("serial", "parallel")


# ---------------------------------------------------------------------------
# Sections
# ---------------------------------------------------------------------------


@dataclass(frozen=True)
class DisplaySettings:
    """Window geometry and the two display-derived timing constants.

    Attributes:
        fullscreen:           Open fullscreen. Also drives ``allowGUI``.
        screen_index:         Monitor to open on; ``None`` auto-detects.
        window_size:          ``[w, h]``; ``None`` uses the screen geometry.
        frame_rate:           Assumed refresh in Hz. Each flip is scheduled one
                              frame early (``onset - 1/frame_rate``), so this
                              must match the real monitor or every trial lands
                              a fraction late.
        instruction_duration: Seconds each instruction screen is shown.
    """

    fullscreen: bool = True
    screen_index: int | None = None
    window_size: tuple[int, int] | None = None
    frame_rate: float = 60.0
    instruction_duration: float = 3.0


@dataclass(frozen=True)
class PathSettings:
    """Where outputs go and where the controller assets come from.

    ``assets_dir`` / ``layout_file`` are both ``None`` by default, meaning
    "use the controller shipped with the package".
    """

    output_root: str = "output"
    assets_dir: str | None = None
    layout_file: str | None = None


@dataclass(frozen=True)
class DesignSettings:
    """Trial structure and timing. See :mod:`controller_validation_task.design`.

    The defaults reproduce the original ``task_stimuli`` task: 8 buttons,
    5 short + 5 long blocks, 80 trials per run, 2 runs, TR-locked jitter.
    """

    keys: tuple[str, ...] = DEFAULT_KEYS
    conditions: tuple[str, ...] = DEFAULT_CONDITIONS
    n_runs: int = 2
    n_blocks_per_condition: int = 5
    short_press_duration: float = 0.3
    long_duration_range: tuple[float, float] = (1.0, 3.0)
    # `tr` is not used for timing or synchronisation — nothing is locked to
    # the scanner clock. It exists only as the scale for the inter-stimulus
    # jitter: leaving `isi_range` and `block_isi` null derives them as
    # (TR, 2*TR) and 2*TR, so gaps between presses land on a spread of
    # TR phases and the HRF gets sampled evenly. Set both explicitly (in
    # seconds) and `tr` stops mattering entirely.
    tr: float = 1.49
    isi_range: tuple[float, float] | None = None
    block_isi: float | None = None
    initial_wait: float = 3.0
    final_wait: float = 9.0
    response_window: float = 1.0
    lr_mode: bool = False
    seed: int | None = None


#: Default keyboard -> button mapping.
#:
#: Two families of key name are accepted out of the box, because
#: fMRI-compatible pads reach the computer in two different ways:
#:
#: * **Arrow keys** (``left``/``right``/``up``/``down``) — what most pads and
#:   the raw HID-to-keyboard adapters emit for the D-pad.
#: * **Letters** (``l``/``r``/``u``/``d``) — what the bundled AntiMicroX
#:   profile emits.
#:
#: Face buttons are ``a``/``b``/``x``/``y`` either way. Mapping both families
#: onto the same four D-pad buttons means either controller works with no
#: configuration; override ``input.key_map`` for anything else.
DEFAULT_KEY_MAP: dict[str, str] = {
    # Arrow keys (pyglet symbol names, lowercased)
    "left": "l",
    "right": "r",
    "up": "u",
    "down": "d",
    # AntiMicroX letter profile
    "l": "l",
    "r": "r",
    "u": "u",
    "d": "d",
    # Face buttons
    "a": "a",
    "b": "b",
    "x": "x",
    "y": "y",
}


@dataclass(frozen=True)
class InputSettings:
    """How keystrokes from the controller map onto controller buttons.

    The task reads the pad as a keyboard. ``key_map`` translates the key name
    PsychoPy reports into the button name used by ``design.keys`` and the
    controller layout, so the same task works whether the pad sends arrow keys
    or letters.

    Several keys may map to the same button (that is how both families above
    coexist). A key that is not in the map is still recorded in
    ``all_keypresses`` — it just never counts as the cued response.
    """

    key_map: dict[str, str] = field(default_factory=lambda: dict(DEFAULT_KEY_MAP))


@dataclass(frozen=True)
class SyncSettings:
    """How the run start is aligned with the recording device.

    ``mode`` says *what happens* at run start:
      * ``"none"`` — start immediately. The default.
      * ``"wait"`` — block until the sync signal arrives.
      * ``"send"`` — emit ``signal`` once, to start the recording device.
        This is the fMRI case where the stimulus computer starts the scanner.

    ``backend`` says *over what*, and defaults to ``"none"`` — no hardware:
      * in ``wait`` mode the signal is then expected from the **keyboard**
        (most MR trigger boxes present as a USB keyboard emitting ``5`` or
        ``t``, so this is also the usual scanner setup);
      * in ``send`` mode there is nothing to send to, so the run starts
        immediately with a warning.

    Otherwise: ``serial`` / ``parallel`` write or read a byte on ``port``,
    ``lsl`` and ``key`` send only, ``keyboard`` waits only, and ``markers``
    (send only) re-uses the already-open outgoing marker backend so a single
    serial port can carry both the start signal and the event markers without
    being opened twice.

    ``signal`` is the sync signal itself, and means the same thing in both
    directions: in ``send`` mode it is what goes out (``"s"`` -> the byte 115),
    in ``wait`` mode it is what we listen for. It may list alternatives, which
    is what a keyboard trigger box usually needs — ``["5", "percent"]`` are the
    same physical key with and without shift. Only the first entry is ever
    sent.

    A ``serial``/``parallel`` port that is unset or will not open degrades to
    the ``"none"`` behaviour above rather than aborting the session.
    """

    mode: SyncMode = "none"
    backend: SyncBackend = "none"
    port: str | None = None
    signal: tuple[str, ...] = ("s",)
    n_dummy_scans: int = 0
    timeout_seconds: float | None = None


@dataclass(frozen=True)
class TriggerSettings:
    """Outgoing event markers for MEG / EEG.

    Independent of :class:`SyncSettings`: a run can wait for a scanner and
    also emit markers, or do neither.
    """

    backend: TriggerBackend = "null"
    port: str | None = None
    lsl_stream_name: str = "controller_validation"
    lsl_stream_type: str = "Markers"
    lsl_stream_source_id: str = "controller_validation_markers"
    codes: TriggerCodes = field(default_factory=TriggerCodes)
    on_trial_onset: bool = True
    on_trial_offset: bool = True
    on_keypress: bool = False


@dataclass(frozen=True)
class Settings:
    """The whole configuration."""

    schema_version: int = SCHEMA_VERSION
    display: DisplaySettings = field(default_factory=DisplaySettings)
    paths: PathSettings = field(default_factory=PathSettings)
    design: DesignSettings = field(default_factory=DesignSettings)
    input: InputSettings = field(default_factory=InputSettings)
    sync: SyncSettings = field(default_factory=SyncSettings)
    triggers: TriggerSettings = field(default_factory=TriggerSettings)


def default_settings() -> Settings:
    """A fresh :class:`Settings` with every default in place."""
    return Settings()


def config_path_default() -> Path:
    """Default config location: ``./config.json`` relative to the cwd."""
    return Path("config.json")


