def _validate(s: Settings) -> None:
    """Raise ``ValueError`` if the configuration cannot produce a valid run."""
    _validate_design(s.design)
    _validate_display(s.display)
    _validate_input(s.input, s.design)
    _validate_sync(s.sync)
    _validate_triggers(s.triggers, s.design)


def _validate_design(d: DesignSettings) -> None:
    if not d.keys:
        raise ValueError("design.keys is empty: there would be no button to cue.")
    if len(set(d.keys)) != len(d.keys):
        raise ValueError(f"design.keys contains duplicates: {d.keys}.")
    if not d.conditions:
        raise ValueError("design.conditions is empty: there would be no trials.")
    if len(set(d.conditions)) != len(d.conditions):
        raise ValueError(f"design.conditions contains duplicates: {d.conditions}.")
    if d.n_runs < 1:
        raise ValueError(f"design.n_runs must be >= 1, got {d.n_runs}.")
    if d.n_blocks_per_condition < 1:
        raise ValueError(
            f"design.n_blocks_per_condition must be >= 1, got {d.n_blocks_per_condition}."
        )
    if d.short_press_duration <= 0:
        raise ValueError(
            f"design.short_press_duration must be > 0, got {d.short_press_duration}."
        )
    lo, hi = d.long_duration_range
    if not (0 < lo <= hi):
        raise ValueError(
            f"design.long_duration_range must be [low, high] with 0 < low <= high, "
            f"got {d.long_duration_range}."
        )
    if d.tr <= 0:
        raise ValueError(f"design.tr must be > 0, got {d.tr} (it seeds the ISI defaults).")
    if d.isi_range is not None:
        ilo, ihi = d.isi_range
        if not (0 < ilo <= ihi):
            raise ValueError(
                f"design.isi_range must be [low, high] with 0 < low <= high, "
                f"got {d.isi_range}. Set it to null to derive [TR, 2*TR]."
            )
    if d.block_isi is not None and d.block_isi < 0:
        raise ValueError(f"design.block_isi must be >= 0, got {d.block_isi}.")
    if d.initial_wait < 0 or d.final_wait < 0:
        raise ValueError("design.initial_wait and design.final_wait must be >= 0.")
    if d.response_window <= 0:
        raise ValueError(
            f"design.response_window must be > 0, got {d.response_window}. It is the "
            f"grace period after a trial's offset during which a late release is "
            f"still attributed to that trial."
        )


def _validate_input(i: InputSettings, d: DesignSettings) -> None:
    if not i.key_map:
        raise ValueError(
            "input.key_map is empty, so no keypress could ever be matched to a "
            "cued button. Restore the default map or list your controller's keys."
        )

    # Entries pointing at buttons this design does not cue are harmless — the
    # default map covers the whole pad, and narrowing design.keys for a pilot
    # is a normal thing to do — so this is a warning, not an error.
    unknown = sorted({v for v in i.key_map.values() if v not in d.keys})
    if unknown:
        log.info(
            "input.key_map maps keys onto %s, which design.keys does not cue; "
            "those entries will simply never match.",
            unknown,
        )

    # The more dangerous direction: a button that is cued but that no key can
    # ever produce. The run would look fine and record no responses for it.
    unreachable = [k for k in d.keys if k not in set(i.key_map.values())]
    if unreachable:
        raise ValueError(
            f"design.keys includes {unreachable}, which no entry of input.key_map "
            f"produces, so those trials could never be answered. Add the key(s) "
            f"your controller sends for them, e.g. {{\"left\": \"{unreachable[0]}\"}}."
        )


def _validate_display(d: DisplaySettings) -> None:
    if d.frame_rate <= 0:
        raise ValueError(
            f"display.frame_rate must be > 0, got {d.frame_rate}. Each flip is "
            f"scheduled one frame early, so this must match the real refresh rate."
        )
    if d.instruction_duration < 0:
        raise ValueError("display.instruction_duration must be >= 0.")
    if d.window_size is not None and (
        len(d.window_size) != 2 or any(v <= 0 for v in d.window_size)
    ):
        raise ValueError(
            f"display.window_size must be [width, height] with positive values, "
            f"got {d.window_size}. Set it to null to use the screen geometry."
        )
    if d.screen_index is not None and d.screen_index < 0:
        raise ValueError("display.screen_index must be >= 0, or null to auto-detect.")


def _validate_sync(s: SyncSettings) -> None:
    valid_modes = ("send", "wait", "none")
    if s.mode not in valid_modes:
        raise ValueError(f"sync.mode must be one of {valid_modes}, got {s.mode!r}.")

    if s.mode != "none" and not s.signal:
        raise ValueError(
            "sync.signal is empty: there would be nothing to send, and nothing "
            "a scanner TTL could match. Most MR trigger boxes emit '5' or 't'."
        )

    if s.mode == "send":
        valid = ("none", "serial", "parallel", "lsl", "key", "markers")
        if s.backend not in valid:
            raise ValueError(
                f"sync.backend for mode 'send' must be one of {valid}, got {s.backend!r}."
            )
        # A missing port is deliberately NOT an error: sync.configure() warns
        # and starts the run anyway, so the same config works at the scanner
        # and on a desk.

    if s.mode == "wait":
        valid = ("none", "keyboard", "serial")
        if s.backend not in valid:
            raise ValueError(
                f"sync.backend for mode 'wait' must be one of {valid}, got {s.backend!r}."
            )
        # As above: no port means fall back to the keyboard, not refuse to run.

    if s.n_dummy_scans < 0:
        raise ValueError(f"sync.n_dummy_scans must be >= 0, got {s.n_dummy_scans}.")
    if s.timeout_seconds is not None and s.timeout_seconds <= 0:
        raise ValueError(
            f"sync.timeout_seconds must be > 0, got {s.timeout_seconds}. "
            f"Set it to null to wait indefinitely."
        )


def _validate_triggers(t: TriggerSettings, d: DesignSettings) -> None:
    valid = ("lsl", "serial", "parallel", "null")
    if t.backend not in valid:
        raise ValueError(f"triggers.backend must be one of {valid}, got {t.backend!r}.")
    if t.backend in _PORT_BACKENDS and not t.port:
        raise ValueError(
            f"triggers.backend is {t.backend!r} but triggers.port is not set, e.g. "
            f"'/dev/ttyACM0' (serial) or '/dev/parport1' (parallel)."
        )

    c = t.codes
    named = {
        "task_start": c.task_start,
        "task_stop": c.task_stop,
        "trial_onset_short": c.trial_onset_short,
        "trial_onset_long": c.trial_onset_long,
        "trial_offset": c.trial_offset,
    }
    # 1. Every marker must fit in the single byte serial/parallel can carry.
    for name, value in {**named, "key_base": c.key_base}.items():
        if not (0 <= value <= 255):
            raise ValueError(
                f"triggers.codes.{name} must be 0..255 (markers are sent as one "
                f"byte on serial/parallel), got {value}."
            )
    # 2. Lifecycle codes must be distinguishable from each other.
    dupes = {v for v in named.values() if list(named.values()).count(v) > 1}
    if dupes:
        raise ValueError(
            f"triggers.codes has duplicate values {sorted(dupes)} among "
            f"{sorted(named)}; each event type needs its own code to be decodable."
        )
    # 3. Per-key codes occupy key_base .. key_base+len(keys)-1 and must not
    #    collide with the lifecycle codes or run off the end of the byte.
    key_span = range(c.key_base, c.key_base + len(d.keys))
    if key_span.stop > 256:
        raise ValueError(
            f"triggers.codes.key_base={c.key_base} plus {len(d.keys)} keys reaches "
            f"{key_span.stop - 1}, past the 255 a one-byte marker can hold. "
            f"Lower key_base or cue fewer buttons."
        )
    overlap = sorted(name for name, value in named.items() if value in key_span)
    if overlap:
        raise ValueError(
            f"triggers.codes.key_base={c.key_base} makes the per-key codes "
            f"{key_span.start}..{key_span.stop - 1} overlap the lifecycle code(s) "
            f"{overlap}. Move key_base above every lifecycle code."
        )
